from typing import Iterable, List, Tuple, Any, Optional
from contextlib import AbstractContextManager

class DBAdapter(AbstractContextManager):
    def connect(self): ...
    def list_columns(self, table: str) -> List[str]: ...
    def ensure_table(self, table: str, pk: str, pk_type: Optional[str] = None): ...
    def ensure_columns(self, table: str, columns: List[Tuple[str, str]]): ...
    def select_pending_rows(self, *,
                            src_table: str, tgt_table: str,
                            pk: str, input_col: str, output_cols: List[str],
                            record_update_time: bool,
                            fetch_size: int = 500,
                            extra_input_cols: Optional[List[str]] = None) -> Iterable[Tuple[Any, str]]:
        ...
    def is_row_pending(self, *, tgt_table: str, pk: str, pk_value: Any, output_cols: List[str]) -> bool:
        ...
    def close(self): ...
    def __exit__(self, exc_type, exc, tb): self.close()
